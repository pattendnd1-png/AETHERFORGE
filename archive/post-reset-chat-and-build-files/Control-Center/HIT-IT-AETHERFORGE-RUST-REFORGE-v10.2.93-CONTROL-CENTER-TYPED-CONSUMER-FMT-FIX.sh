log() { printf '%s\n' "$*" | tee -a "$VERIFY"; }
hash_path() {
  local p="$1"
  if [[ -f "$p" || -L "$p" ]]; then sha256sum "$p" | awk '{print $1}'
  elif [[ -d "$p" ]]; then printf 'DIRECTORY'
  else printf 'MISSING'; fi
}
rollback() {
  log "TYPED_CONSUMER_ROLLBACK=START"
  if [[ -f "$BACKUP_CONSUMER" ]]; then
    install -m755 "$BACKUP_CONSUMER" "$CONSUMER" >>"$VERIFY" 2>&1 || true
    local rollback_sha
    rollback_sha="$(hash_path "$CONSUMER")"
    log "TYPED_CONSUMER_ROLLBACK_SHA256=$rollback_sha"
    if [[ "$rollback_sha" = "$EXPECTED_CONSUMER_SHA" ]]; then
      log "TYPED_CONSUMER_ROLLBACK=PASS"
    else
      log "TYPED_CONSUMER_ROLLBACK=FAIL"
    fi
  else
    log "TYPED_CONSUMER_ROLLBACK=FAIL:BACKUP_MISSING"
  fi
}
fail() {
  rc="${1:-1}"; shift || true
  log "${*:-AETHERFORGE_CONTROL_CENTER_TYPED_CONSUMER_FAILED}"
  if [[ "$INSTALLED" = 1 ]]; then rollback; fi
  log "AETHERFORGE_CONTROL_CENTER_TYPED_CONSUMER_FMT_FIX=FAIL"
  log "VERIFY_FILE=$VERIFY"
  exit "$rc"
}

